#!/usr/bin/env node
/**
 * Writes dist/sw.js after `expo export -p web`: a service worker that stores every file of the
 * build on the phone at install, so the home-screen app opens and runs offline (audio included).
 * The cache name is a hash of the build, so a new deploy installs fresh and drops the old copy.
 * It also opens the right screen when a reminder notification is tapped (src/lib/notify.web.ts).
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIST = join(fileURLToPath(new URL('.', import.meta.url)), '..', 'dist');
const SKIP = new Set(['sw.js', 'metadata.json', 'index.html']);

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

const hash = createHash('sha256');
const files = walk(DIST)
  .map((p) => relative(DIST, p).split(sep).join('/'))
  .filter((f) => !SKIP.has(f))
  .sort();
for (const f of [...files, 'index.html']) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const urls = ['/', ...files.map((f) => encodeURI('/' + f))];

const sw = `// Generated by scripts/gen-sw.mjs. Do not edit.
const CACHE = 'athkarna-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // A few at a time: phones drop the install when hundreds of requests start at once.
    for (let i = 0; i < PRECACHE.length; i += 8) {
      await cache.addAll(PRECACHE.slice(i, i + 8).map((u) => new Request(u, { cache: 'reload' })));
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('athkarna-') && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

/** Safari plays audio only from 206 range responses, so ranges are cut from the stored file. */
async function ranged(request, response) {
  const m = /bytes=(\\d*)-(\\d*)/.exec(request.headers.get('range') || '');
  if (!m) return response;
  const blob = await response.blob();
  const start = m[1] ? Number(m[1]) : Math.max(0, blob.size - Number(m[2]));
  const end = m[1] && m[2] ? Math.min(Number(m[2]), blob.size - 1) : blob.size - 1;
  return new Response(blob.slice(start, end + 1), {
    status: 206,
    headers: {
      'Content-Type': response.headers.get('Content-Type') || 'application/octet-stream',
      'Content-Range': \`bytes \${start}-\${end}/\${blob.size}\`,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  });
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Every route is the same single page: the newest from the network, the stored one offline.
    event.respondWith(
      fetch('/', { cache: 'no-cache' })
        .then((res) => (res.ok ? res : Promise.reject(res)))
        .catch(() => caches.match('/', { cacheName: CACHE })),
    );
    return;
  }
  event.respondWith((async () => {
    const cached = await caches.match(request.url, { cacheName: CACHE, ignoreSearch: true });
    if (cached) return request.headers.has('range') ? ranged(request, cached) : cached;
    return fetch(request);
  })());
});

// A tapped reminder opens its screen: in the open app if there is one, else in a new window.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || '/';
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of windows) {
      if ('focus' in client) {
        await client.focus();
        client.postMessage({ type: 'open', url });
        return;
      }
    }
    await self.clients.openWindow(url);
  })());
});
`;

writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files, cache athkarna-${version}`);
