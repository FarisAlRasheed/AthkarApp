#!/usr/bin/env node
/**
 * Generates src/content/sound-index.ts: one static require per file in assets/sounds (Metro can't
 * require dynamic paths). Folders:
 *   beads/   bead-*.wav|m4a|mp3 (variants, picked at random), separator.*, imam.*
 *   count/   tap-*.* (variants)
 *   ambient/ <key>.* — fajr, morning, asr, maghrib, night (follow the sky) and rain
 * Adding a recording = drop the file in, run this script. Nothing else changes.
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOUNDS = join(ROOT, 'assets', 'sounds');
const AUDIO = new Set(['.wav', '.m4a', '.mp3', '.aac']);
const list = (dir) => (existsSync(join(SOUNDS, dir)) ? readdirSync(join(SOUNDS, dir)).filter((f) => AUDIO.has(extname(f))).sort() : []);
const req = (dir, f) => `require('../../assets/sounds/${dir}/${f}')`;

const beads = list('beads');
const pick = (files, prefix) => files.filter((f) => basename(f, extname(f)).startsWith(prefix)).map((f) => req('beads', f));
const count = list('count').map((f) => req('count', f));
const ambient = list('ambient').map((f) => `    '${basename(f, extname(f))}': ${req('ambient', f)},`);

const out = `// Generated by scripts/gen-sound-index.mjs. Do not edit.
export const SOUNDS = {
  bead: [${pick(beads, 'bead').join(', ')}] as number[],
  separator: [${pick(beads, 'separator').join(', ')}] as number[],
  imam: [${pick(beads, 'imam').join(', ')}] as number[],
  count: [${count.join(', ')}] as number[],
  ambient: {
${ambient.join('\n')}
  } as Record<string, number>,
};
`;
writeFileSync(join(ROOT, 'src', 'content', 'sound-index.ts'), out);
console.log(`sound-index.ts: ${beads.length} bead, ${count.length} count, ${ambient.length} ambient`);
