'use strict';

const GRADES = ['صحيح', 'حسن', 'ضعيف', 'موضوع'];
const ID_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const state = {
  content: null,
  dirty: false,
  view: 'athkar',
  selected: null,
  search: '',
  book: null,
  chapter: 0,
  reciter: null,
  newIds: new Set(),
};

const $ = (sel) => document.querySelector(sel);

function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v == null || v === false) continue;
    if (k.startsWith('on')) el.addEventListener(k.slice(2), v);
    else if (k === 'class') el.className = v;
    else if (k === 'value' || k === 'checked') el[k] = v;
    else el.setAttribute(k, v === true && !k.startsWith('aria-') ? '' : v);
  }
  for (const c of children.flat()) {
    if (c != null && c !== false) el.append(c instanceof Node ? c : String(c));
  }
  return el;
}

const normalize = (t) => t
  .replace(/[ؐ-ًؚ-ٰٟۖ-ۭـ]/g, '')
  .replace(/[ٱأإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه');

const toArabicDigits = (n) => String(n).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[d]);

// ---------- data helpers ----------

const C = () => state.content;

// A book with a Turath source is generated by `npm run content:books` from its recipe — read-only here.
const isBuilt = (bookId) => !!C().books[bookId]?.source;
const bookLabel = (b) => (b.title ? `${b.title} — ${b.author}` : b.author ?? '');
const sectionTitle = (sid) => C().sections.sections[sid]?.title ?? sid;

function usagesOf(id) {
  const out = [];
  for (const bookId of C().manifest.books) {
    C().books[bookId].chapters.forEach((chapter, ci) => {
      chapter.entries.forEach((entry, index) => { if (entry.id === id) out.push({ bookId, chapter, ci, index, entry }); });
    });
  }
  return out;
}

const isRecorded = (id, reciter = state.reciter) => C().reciters[reciter]?.recorded.includes(id);

function setOptional(obj, key, value) {
  if (value.trim()) obj[key] = value; else delete obj[key];
}

// num is left out for once (the validator wants a whole number > 1).
function setNum(entry, value) {
  const n = Math.floor(Number(value));
  if (n > 1) entry.num = n; else delete entry.num;
}

// Hand-made books own the hadiths named after them (uthaymeen-morning-12); built books' come from Turath.
const ownsHadith = (bookId, hid) => !isBuilt(bookId) && !!hid?.startsWith(`${bookId}-`);

function newHadithId(bookId) {
  let n = 1;
  while (C().hadiths[`${bookId}-${n}`]) n += 1;
  return `${bookId}-${n}`;
}

function markDirty() {
  state.dirty = true;
  $('#save').disabled = false;
  $('#status').textContent = 'تعديلات غير محفوظة';
}

function nextNewId() {
  let n = Object.keys(C().athkar).length + 1;
  while (C().athkar[`thiker-${n}`]) n += 1;
  return `thiker-${n}`;
}

function renameThiker(oldId, newId) {
  const renamed = {};
  for (const [k, v] of Object.entries(C().athkar)) renamed[k === oldId ? newId : k] = v;
  C().athkar = renamed;
  for (const u of usagesOf(oldId)) u.entry.id = newId;
  state.newIds.delete(oldId);
  state.newIds.add(newId);
  state.selected = newId;
}

// ---------- server ----------

async function load() {
  const res = await fetch('/api/content');
  state.content = await res.json();
  state.reciter ??= Object.keys(C().reciters)[0];
  state.book ??= C().manifest.books.find((b) => !isBuilt(b)) ?? C().manifest.defaultBook;
  render();
}

async function save() {
  $('#save').disabled = true;
  $('#status').textContent = 'جارٍ الحفظ…';
  const res = await fetch('/api/content', {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(C()),
  });
  const body = await res.json();
  if (!res.ok) {
    showProblems(body.errors ?? [body.error], body.warnings);
    $('#status').textContent = 'لم يُحفظ — صحّح الأخطاء';
    $('#save').disabled = false;
    return;
  }
  C().manifest.contentVersion = body.contentVersion;
  state.dirty = false;
  state.newIds.clear();
  showProblems([], body.warnings);
  $('#status').textContent = `تم الحفظ — إصدار المحتوى ${toArabicDigits(body.contentVersion)}`;
  render();
}

function showProblems(errors, warnings = []) {
  const box = $('#problems');
  const lines = [...errors.map((e) => `✗ ${e}`), ...warnings.map((w) => `! ${w}`)];
  box.hidden = !lines.length;
  box.classList.toggle('ok', !errors.length);
  box.textContent = lines.join('\n');
  if (errors.length) window.scrollTo({ top: 0, behavior: 'smooth' });
}

async function uploadAudio(id, file) {
  const res = await fetch(`/api/audio/${state.reciter}/${id}`, { method: 'PUT', body: file });
  const body = await res.json();
  if (!res.ok) { alert(body.error); return; }
  C().reciters = body.reciters;
  render();
}

async function deleteAudio(id, reciter = state.reciter) {
  const res = await fetch(`/api/audio/${reciter}/${id}`, { method: 'DELETE' });
  C().reciters = (await res.json()).reciters;
}

// ---------- rendering ----------

function render() {
  document.querySelectorAll('.views button').forEach((b) => b.setAttribute('aria-pressed', b.dataset.view === state.view));
  const main = $('#main');
  main.replaceChildren(state.view === 'athkar' ? renderAthkarView() : renderBooksView());
  main.querySelector('.item[aria-current="true"]')?.scrollIntoView({ block: 'nearest' });
}

function renderAthkarView() {
  return h('div', { class: 'split' }, renderAthkarList(), h('div', { id: 'editor' }, renderThikerEditor()));
}

function renderAthkarList() {
  const list = h('div', { class: 'list' });
  const fill = () => {
    const q = normalize(state.search.trim());
    list.replaceChildren(...Object.entries(C().athkar)
      .filter(([id, t]) => !q || normalize(`${t.title} ${t.text} ${id}`).includes(q))
      .map(([id, t]) => {
        const uses = usagesOf(id).length;
        return h('button', {
          type: 'button', class: 'item', 'aria-current': id === state.selected,
          onclick: () => { state.selected = id; render(); },
        },
        h('span', { class: 'badges' }, isRecorded(id) ? '🔊 ' : '', uses ? `${toArabicDigits(uses)} موضع` : '⚠ غير مستخدم'),
        t.title, h('small', {}, id));
      }));
  };
  fill();
  return h('aside', { class: 'panel list-panel' },
    h('div', { class: 'row' },
      h('input', { type: 'search', placeholder: 'بحث في الأذكار…', value: state.search, oninput: (e) => { state.search = e.target.value; fill(); } }),
      h('button', { type: 'button', class: 'fit primary', onclick: addThiker }, '+ ذكر جديد')),
    list);
}

function addThiker() {
  const id = nextNewId();
  C().athkar[id] = { title: 'ذكر جديد', text: '' };
  state.newIds.add(id);
  state.selected = id;
  state.search = '';
  markDirty();
  render();
}

function renderThikerEditor() {
  const id = state.selected;
  const t = C().athkar[id];
  if (!t) return h('div', { class: 'panel muted' }, 'اختر ذكرًا من القائمة، أو أنشئ ذكرًا جديدًا.');
  const uses = usagesOf(id);
  const preview = h('div', { class: `preview arabic${t.quran ? ' quran' : ''}` }, t.text || '…');

  return h('div', { class: 'stack' },
    h('div', { class: 'panel stack' },
      h('div', { class: 'row' },
        h('h2', {}, t.title),
        h('button', {
          type: 'button', class: 'fit danger', disabled: uses.length > 0,
          title: uses.length ? 'احذفه من جميع الكتب أولًا' : '',
          onclick: () => removeThiker(id),
        }, 'حذف الذكر')),
      state.newIds.has(id)
        ? h('div', {},
          h('label', {}, 'المعرّف (بالإنجليزية، لا يتغيّر بعد الحفظ)'),
          h('input', {
            dir: 'ltr', value: id,
            onchange: (e) => {
              const next = e.target.value.trim();
              if (next === id) return;
              if (!ID_PATTERN.test(next)) { alert('أحرف إنجليزية صغيرة وأرقام وشرطات فقط، مثل: morning-dua'); e.target.value = id; return; }
              if (C().athkar[next]) { alert('هذا المعرّف مستخدم'); e.target.value = id; return; }
              renameThiker(id, next);
              markDirty();
              render();
            },
          }))
        : h('p', { class: 'muted', dir: 'ltr' }, id),
      h('div', {},
        h('label', {}, 'العنوان'),
        h('input', { value: t.title, oninput: (e) => { t.title = e.target.value; markDirty(); }, onchange: render })),
      h('div', {},
        h('label', {}, 'النص'),
        h('textarea', {
          class: 'arabic', rows: 6, value: t.text, readOnly: !!t.ayahs,
          oninput: (e) => { t.text = e.target.value; preview.textContent = t.text || '…'; markDirty(); },
        }),
        // Quranic text comes from the KFGQPC Hafs data (npm run content:quran), never typed by hand.
        t.ayahs
          ? h('p', { class: 'muted' },
            `نص قرآني من مصحف مجمع الملك فهد (سورة ${toArabicDigits(t.ayahs.sura)}، الآيات ${toArabicDigits(t.ayahs.from)}–${toArabicDigits(t.ayahs.to)}) — يُحدَّث بالأمر npm run content:quran`)
          : null,
        // npm run content:books keeps the most fully vocalised wording, so a hand edit can be replaced there.
        !t.ayahs && uses.some((u) => isBuilt(u.bookId))
          ? h('p', { class: 'muted' }, 'تستعمله كتب مبنية من تراث: إن أعاد البناء (npm run content:books) نصًا أكمل تشكيلًا حلّ محل تعديلك.')
          : null),
      h('label', { class: 'row' },
        h('input', {
          type: 'checkbox', class: 'fit', checked: !!t.quran,
          onchange: (e) => { if (e.target.checked) t.quran = true; else delete t.quran; preview.classList.toggle('quran', !!t.quran); markDirty(); },
        }),
        h('span', {}, 'نص قرآني')),
      h('div', {}, h('label', {}, 'معاينة'), preview)),
    renderAudio(id),
    h('div', { class: 'panel stack' },
      h('h3', {}, `المواضع (${toArabicDigits(uses.length)}) — التكرار والفضل والدليل`),
      uses.length ? null : h('p', { class: 'muted' }, 'هذا الذكر غير مستخدم في أي كتاب بعد.'),
      uses.some((u) => isBuilt(u.bookId))
        ? h('p', { class: 'muted' }, 'مواضع الكتب المبنية من تراث للعرض فقط — تُعدَّل في وصفاتها (scripts/books) ثم npm run content:books.')
        : null,
      ...uses.map(renderUsage),
      renderQuickAdd(id)));
}

function renderAudio(id) {
  const reciterIds = Object.keys(C().reciters);
  const recorded = isRecorded(id);
  return h('div', { class: 'panel stack' },
    h('div', { class: 'row' },
      h('h3', {}, 'التسجيل الصوتي'),
      reciterIds.length > 1
        ? h('select', { class: 'fit', onchange: (e) => { state.reciter = e.target.value; render(); } },
          reciterIds.map((r) => h('option', { value: r, selected: r === state.reciter }, C().reciters[r].name)))
        : h('span', { class: 'fit muted' }, C().reciters[state.reciter].name)),
    recorded ? h('audio', { controls: true, src: `/audio/${state.reciter}/${id}.m4a?t=${Date.now()}` }) : h('p', { class: 'muted' }, 'لا يوجد تسجيل لهذا الذكر.'),
    state.newIds.has(id)
      ? h('p', { class: 'muted' }, 'احفظ الذكر أولًا ثم ارفع التسجيل.')
      : h('div', { class: 'row' },
        h('label', { class: 'fit' }, recorded ? 'استبدال التسجيل (m4a):' : 'رفع تسجيل (m4a):'),
        h('input', { type: 'file', accept: '.m4a,audio/mp4,audio/x-m4a', onchange: (e) => e.target.files[0] && uploadAudio(id, e.target.files[0]) }),
        recorded ? h('button', {
          type: 'button', class: 'fit danger',
          onclick: async () => { if (confirm('حذف التسجيل؟')) { await deleteAudio(id); render(); } },
        }, 'حذف التسجيل') : null));
}

function renderUsage(u) {
  const { entry, bookId, chapter } = u;
  const book = C().books[bookId];
  const hadith = entry.hadith ? C().hadiths[entry.hadith] : null;
  return h('div', { class: 'usage' },
    h('header', {},
      h('strong', {}, `${bookLabel(book)} · ${chapter.title} · الموضع ${toArabicDigits(u.index + 1)}`),
      h('button', { type: 'button', class: 'link', onclick: () => { state.view = 'books'; state.book = bookId; state.chapter = u.ci; render(); } }, 'فتح الباب')),
    isBuilt(bookId)
      ? h('p', { class: 'muted' },
        `التكرار ${toArabicDigits(entry.num ?? 1)}`,
        entry.note ? ` · ${entry.note}` : '',
        entry.fadl ? ` · ${entry.fadl}` : '',
        hadith ? ` · ${hadith.grade ?? ''} ${hadith.source}` : '')
      : h('div', {},
        h('div', { class: 'row' },
          h('div', { class: 'fit' },
            h('label', {}, 'التكرار'),
            h('input', { type: 'number', min: 1, value: entry.num ?? 1, style: 'width:90px', oninput: (e) => { setNum(entry, e.target.value); markDirty(); } })),
          h('div', {},
            h('label', {}, 'متى وكيف (اختياري)'),
            h('input', { value: entry.note ?? '', oninput: (e) => { setOptional(entry, 'note', e.target.value); markDirty(); } }))),
        h('label', {}, 'فضل الذكر (بلفظ هذا الكتاب)'),
        h('textarea', { rows: 2, value: entry.fadl ?? '', oninput: (e) => { setOptional(entry, 'fadl', e.target.value); markDirty(); } }),
        renderHadithPicker(bookId, entry)));
}

// The evidence an entry points at: any hadith in the pool, or a new one this book owns and edits.
function renderHadithPicker(bookId, entry) {
  const hid = entry.hadith;
  const hd = hid ? C().hadiths[hid] : null;
  const field = (key, label, { rows, wide, placeholder } = {}) => h('div', { class: wide ? 'wide' : '' },
    h('label', {}, label),
    h(rows ? 'textarea' : 'input', {
      rows, placeholder, value: hd[key] ?? '',
      oninput: (e) => { setOptional(hd, key, e.target.value); markDirty(); },
    }));
  return h('div', {},
    h('label', {}, 'الدليل'),
    h('div', { class: 'row' },
      h('input', {
        dir: 'ltr', list: 'hadith-options', value: hid ?? '', placeholder: 'معرّف الحديث، مثل hisn-75',
        onchange: (e) => {
          const next = e.target.value.trim();
          if (next && !C().hadiths[next]) { alert('لا يوجد حديث بهذا المعرّف'); e.target.value = hid ?? ''; return; }
          if (next) entry.hadith = next; else delete entry.hadith;
          markDirty();
          render();
        },
      }),
      h('button', {
        type: 'button', class: 'fit',
        onclick: () => {
          const id = newHadithId(bookId);
          C().hadiths[id] = { source: '' };
          entry.hadith = id;
          markDirty();
          render();
        },
      }, '+ دليل جديد')),
    h('datalist', { id: 'hadith-options' }, Object.keys(C().hadiths).map((k) => h('option', { value: k }))),
    !hd ? null : ownsHadith(bookId, hid)
      ? h('div', { class: 'evidence' },
        field('text', 'نص الحديث', { rows: 3, wide: true }),
        field('source', 'المصدر والتخريج (مطلوب)', { placeholder: 'مثال: رواه مسلم (٢٧٢٣)' }),
        h('div', {},
          h('label', {}, 'الدرجة'),
          h('select', { onchange: (e) => { setOptional(hd, 'grade', e.target.value); markDirty(); } },
            h('option', { value: '' }, '—'),
            GRADES.map((g) => h('option', { value: g, selected: hd.grade === g }, g)))),
        field('fadl', 'الفضل كما في الحديث', { wide: true }),
        field('gradeNote', 'ملاحظة على الدرجة (اختياري)', { wide: true, placeholder: 'مثال: صححه الألباني' }))
      : h('p', { class: 'muted' }, `${hd.grade ?? ''} ${hd.source}${hd.fadl ? ` — ${hd.fadl}` : ''} (حديث من كتاب آخر، للعرض فقط)`));
}

function renderQuickAdd(id) {
  const targets = C().manifest.books.filter((b) => !isBuilt(b))
    .flatMap((b) => C().books[b].chapters.map((ch, ci) => ({ value: `${b}/${ci}`, label: `${bookLabel(C().books[b])} · ${ch.title}` })));
  if (!targets.length) return null;
  const sel = h('select', {}, targets.map((t) => h('option', { value: t.value }, t.label)));
  const num = h('input', { type: 'number', min: 1, value: 1 });
  return h('div', { class: 'usage' },
    h('h3', {}, 'إضافة إلى باب'),
    h('div', { class: 'row' },
      sel, h('div', { class: 'fit', style: 'width:90px' }, num),
      h('button', {
        type: 'button', class: 'fit',
        onclick: () => {
          const [b, ci] = sel.value.split('/');
          const entry = { id };
          setNum(entry, num.value);
          C().books[b].chapters[Number(ci)].entries.push(entry);
          markDirty();
          render();
        },
      }, 'إضافة في آخر الباب')));
}

function removeThiker(id) {
  if (!confirm(`حذف «${C().athkar[id].title}»؟ (يُحذف تسجيله أيضًا عند الحفظ)`)) return;
  delete C().athkar[id];
  state.newIds.delete(id);
  state.selected = null;
  markDirty();
  render();
}

// ---------- books view ----------

function renderBooksView() {
  const m = C().manifest;
  if (!C().books[state.book]) state.book = m.defaultBook;
  const book = C().books[state.book];
  const built = isBuilt(state.book);
  if (!book.chapters[state.chapter]) state.chapter = 0;
  const chapter = book.chapters[state.chapter];

  return h('div', { class: 'stack' },
    h('div', { class: 'panel' },
      h('div', { class: 'tabs' },
        m.books.map((b) => h('button', {
          type: 'button', 'aria-pressed': b === state.book,
          onclick: () => { state.book = b; state.chapter = 0; render(); },
        }, bookLabel(C().books[b]), b === m.defaultBook ? ' ★' : '')),
        h('button', { type: 'button', onclick: addBook }, '+ كتاب جديد')),
      built
        ? h('p', { class: 'muted' },
          `مبني من مكتبة تراث (${book.source.turath}) — للعرض فقط. عدّل scripts/books/${state.book}.recipe.mjs ثم شغّل npm run content:books.`)
        : h('div', { class: 'row' },
          h('div', {}, h('label', {}, 'اسم الكتاب (اختياري)'),
            h('input', { value: book.title ?? '', oninput: (e) => { setOptional(book, 'title', e.target.value); markDirty(); }, onchange: render })),
          h('div', {}, h('label', {}, 'المؤلف'),
            h('input', { value: book.author ?? '', oninput: (e) => { setOptional(book, 'author', e.target.value); markDirty(); }, onchange: render }))),
      h('div', { class: 'row', style: 'margin-top:10px' },
        h('div', { class: 'fit' },
          h('button', {
            type: 'button', disabled: state.book === m.defaultBook,
            onclick: () => { m.defaultBook = state.book; markDirty(); render(); },
          }, state.book === m.defaultBook ? '★ الافتراضي للأوراد عند المستخدمين الجدد' : 'اجعله الافتراضي للأوراد')),
        built ? null : h('div', { class: 'fit' },
          h('button', { type: 'button', class: 'danger', disabled: state.book === m.defaultBook, onclick: removeBook }, 'حذف الكتاب')))),
    h('div', { class: 'panel' },
      h('div', { class: 'tabs' },
        book.chapters.map((ch, ci) => h('button', {
          type: 'button', 'aria-pressed': ci === state.chapter,
          onclick: () => { state.chapter = ci; render(); },
        }, `${ch.title} (${toArabicDigits(ch.entries.length)})`)),
        built ? null : h('button', { type: 'button', onclick: () => addChapter(book) }, '+ باب جديد')),
      chapter ? renderChapter(book, chapter, built) : h('p', { class: 'muted' }, 'لا أبواب في هذا الكتاب بعد.')));
}

function renderChapter(book, chapter, built) {
  const { groups, sections } = C().sections;
  const isWird = chapter.sections.some((sid) => sections[sid]?.kind === 'wird');
  return h('div', { class: 'stack' },
    built ? null : h('div', { class: 'row' },
      h('div', {}, h('label', {}, 'عنوان الباب'),
        h('input', { value: chapter.title, oninput: (e) => { chapter.title = e.target.value; markDirty(); }, onchange: render })),
      h('div', { class: 'fit' }, h('label', {}, ' '),
        h('button', {
          type: 'button', class: 'danger',
          onclick: () => {
            if (!confirm(`حذف باب «${chapter.title}» بكل مواضعه؟`)) return;
            book.chapters.splice(state.chapter, 1);
            state.chapter = Math.max(0, state.chapter - 1);
            markDirty();
            render();
          },
        }, 'حذف الباب'))),
    h('div', {},
      h('label', {}, 'يظهر في أقسام التطبيق'),
      built
        ? h('p', {}, chapter.sections.map(sectionTitle).join('، ') || '—')
        : h('select', {
          multiple: true, size: 8,
          onchange: (e) => {
            chapter.sections = [...e.target.selectedOptions].map((o) => o.value);
            for (const en of chapter.entries) if (en.only && !chapter.sections.includes(en.only)) delete en.only;
            markDirty();
            render();
          },
        }, Object.entries(groups).map(([g, gt]) => h('optgroup', { label: gt },
          Object.entries(sections).filter(([, s]) => s.group === g)
            .map(([sid, s]) => h('option', { value: sid, selected: chapter.sections.includes(sid) }, `${s.title}${s.kind === 'wird' ? ' (ورد)' : ''}`)))))),
    renderEntries(chapter, built, isWird));
}

function renderEntries(chapter, built, isWird) {
  const list = chapter.entries;
  const move = (i, d) => { [list[i], list[i + d]] = [list[i + d], list[i]]; markDirty(); render(); };
  // Chapters shared by morning and evening mark the entries said in only one of them.
  const shared = chapter.sections.length > 1;

  const onlyCell = (e) => {
    if (!shared || e.guide !== undefined) return '';
    if (built) return e.only ? sectionTitle(e.only) : 'الكل';
    return h('select', { onchange: (ev) => { setOptional(e, 'only', ev.target.value); markDirty(); } },
      h('option', { value: '' }, 'الكل'),
      chapter.sections.map((sid) => h('option', { value: sid, selected: e.only === sid }, sectionTitle(sid))));
  };

  const rows = list.map((e, i) => h('tr', {},
    h('td', {}, toArabicDigits(i + 1)),
    e.guide !== undefined
      ? h('td', { colspan: 2 }, built
        ? h('span', { class: 'muted' }, `إرشاد: ${e.guide}`)
        : h('input', { value: e.guide, oninput: (ev) => { e.guide = ev.target.value; markDirty(); } }))
      : h('td', {}, h('button', {
        type: 'button', class: 'link',
        onclick: () => { state.view = 'athkar'; state.selected = e.id; render(); },
      }, C().athkar[e.id]?.title ?? `⚠ ${e.id}`)),
    e.guide !== undefined ? null : h('td', { class: 'num' }, built
      ? toArabicDigits(e.num ?? 1)
      : h('input', { type: 'number', min: 1, value: e.num ?? 1, oninput: (ev) => { setNum(e, ev.target.value); markDirty(); } })),
    h('td', {}, onlyCell(e)),
    h('td', {}, e.id && isRecorded(e.id) ? '🔊' : '—'),
    h('td', {}, e.fadl || e.hadith ? '✓' : '—'),
    built ? h('td', {}) : h('td', { class: 'actions' },
      h('button', { type: 'button', disabled: i === 0, onclick: () => move(i, -1), title: 'للأعلى' }, '▲'),
      h('button', { type: 'button', disabled: i === list.length - 1, onclick: () => move(i, 1), title: 'للأسفل' }, '▼'),
      h('button', {
        type: 'button', class: 'danger', title: 'إزالة من الباب',
        onclick: () => { if (confirm('إزالة هذا الموضع من الباب؟')) { list.splice(i, 1); markDirty(); render(); } },
      }, '✕'))));

  const table = h('table', {},
    h('thead', {}, h('tr', {}, h('th', {}, '#'), h('th', {}, 'الذكر'), h('th', {}, 'التكرار'), h('th', {}, shared ? 'القسم' : ''), h('th', {}, 'صوت'), h('th', {}, 'فضل/دليل'), h('th', {}, ''))),
    h('tbody', {}, rows));
  if (built) return table;

  const options = Object.entries(C().athkar).map(([id, t]) => h('option', { value: `${t.title} — ${id}` }));
  const pick = h('input', { list: 'athkar-options', placeholder: 'ابحث عن ذكر لإضافته…' });
  const num = h('input', { type: 'number', min: 1, value: 1 });
  return h('div', {},
    table,
    h('datalist', { id: 'athkar-options' }, options),
    h('div', { class: 'row', style: 'margin-top:12px' },
      pick, h('div', { class: 'fit', style: 'width:90px' }, num),
      h('button', {
        type: 'button', class: 'fit primary',
        onclick: () => {
          const id = pick.value.split(' — ').pop();
          if (!C().athkar[id]) { alert('اختر ذكرًا من القائمة'); return; }
          const entry = { id };
          setNum(entry, num.value);
          list.push(entry);
          markDirty();
          render();
        },
      }, 'إضافة'),
      // A guide is a line of guidance with no words to say — reading lists only, never in a wird.
      isWird ? null : h('button', {
        type: 'button', class: 'fit',
        onclick: () => { list.push({ guide: 'إرشاد' }); markDirty(); render(); },
      }, '+ إرشاد')),
    h('p', { class: 'muted' }, 'لإنشاء ذكر جديد غير موجود: من تبويب «الأذكار» ← «+ ذكر جديد».'));
}

function addChapter(book) {
  const title = prompt('عنوان الباب:')?.trim();
  if (!title) return;
  book.chapters.push({ title, sections: [], entries: [] });
  state.chapter = book.chapters.length - 1;
  markDirty();
  render();
}

function addBook() {
  const id = prompt('معرّف الكتاب بالإنجليزية (مثال: albani):')?.trim();
  if (!id) return;
  if (!ID_PATTERN.test(id) || C().books[id]) { alert('معرّف غير صالح أو مستخدم'); return; }
  const author = prompt('المؤلف (مثال: الألباني):')?.trim();
  if (!author) return;
  C().books[id] = { author, chapters: [] };
  C().manifest.books.push(id);
  state.book = id;
  state.chapter = 0;
  markDirty();
  render();
}

function removeBook() {
  if (!confirm(`حذف كتاب «${bookLabel(C().books[state.book])}» بكل أبوابه؟`)) return;
  // Its own hadiths go with it; a hadith another book still cites stays (the validator would flag it).
  const stillCited = new Set(C().manifest.books.filter((b) => b !== state.book)
    .flatMap((b) => C().books[b].chapters.flatMap((ch) => ch.entries.map((e) => e.hadith))));
  for (const hid of Object.keys(C().hadiths)) if (ownsHadith(state.book, hid) && !stillCited.has(hid)) delete C().hadiths[hid];
  delete C().books[state.book];
  C().manifest.books = C().manifest.books.filter((b) => b !== state.book);
  state.book = C().manifest.defaultBook;
  markDirty();
  render();
}

